// Campaign · Black Friday 2026 · a plain letter from Shadi to Mate Latte buyers who are not subscribed
//
// Audience: ordered the Mate Latte at least once, no active subscription.
// Job (Bernat, 2026-11-12): the same Black Friday gift as bf-shadi, written for people who have
// already tried it. The angle: you know you like it, so join the club at the biggest discount of the year and
// never run out. Short, friendly, one link (the Starter Kit, 30 servings).
//
// Facts used (Shopify, 2026-11-12): Starter Kit plan 8837562678, 40% off the first box, then 30% off every
// monthly box; frother + scooper free with 30 and 60 servings; skip, pause or cancel anytime. No sale dates.
//
// Writes exports/klaviyo/bf-shadi-buyers/bf-shadi-buyers.html (full document, for a code template) + .txt, preview in refine/.
// Usage: node scripts/make-bf-shadi-buyers.mjs
import fs from 'node:fs';
import { validate } from './validate-klaviyo-email.mjs';

const OUT = 'exports/klaviyo/bf-shadi-buyers';
fs.mkdirSync(OUT, { recursive: true });
export const SUBJECT = 'you already know it’s good ☕';
export const PREHEADER = 'So here’s 40% off your first Mate Mornings Club box, on me.';
const utm = (slot) => `utm_source=klaviyo&utm_medium=email&utm_campaign=black_friday_2026&utm_content=${slot}`;
const KIT = `https://milonga.life/products/the-original-mate-latte?selling_plan=8837562678&variant=54302750245174&${utm('shadi_buyers_kit_link')}`;

// [kind, ...]. 'p' text · 'l' [before, link text, after, href] · 'sign' · 'ps' [before, link text, after, href]
const LETTER = [
  ['p', 'Hey {{ person.first_name|default:\'there\' }}!'],
  ['p', 'Shadi here. You’ve already tried the Mate Latte, so first of all, thank you. It really means a lot. 💛'],
  ['p', 'Quick question: did your last bag run out faster than you expected? 😄 Then you know the feeling of reaching for it on a busy morning and finding it empty.'],
  ['p', 'So for Black Friday, I have a little gift for you: 40% off your first box when you join the Mate Mornings Club. With 30 or 60 servings, the frother and scooper are on me.'],
  ['l', '', 'Claim my 40% off', '', KIT],
  ['p', 'It’s our biggest discount of the year. After that, you still save 30% on every box, it shows up at your door every month, and you can skip, pause or cancel anytime.'],
  ['p', 'Any questions? Just hit reply. I read every one.'],
  ['sign', 'Un abrazo,', 'Shadi'],
];

const ent = (s) => s.replace(/&/g, '&amp;').replace(/’/g, '&rsquo;').replace(/‘/g, '&lsquo;').replace(/“/g, '&ldquo;').replace(/”/g, '&rdquo;').replace(/…/g, '&hellip;').replace(/—/g, '&mdash;').replace(/–/g, '&ndash;');
const P = (inner, last) => `<p style="margin:0 0 ${last ? 0 : 18}px;">${inner}</p>`;
const A = (href, text) => `<a href="${href.replace(/&/g, '&amp;')}" target="_blank" style="color:#004D27;font-weight:bold;text-decoration:underline;">${ent(text)}</a>`;

function html() {
  const rows = LETTER.map(([k, a, b, c, d], i) => {
    if (k === 'l') return P(`${ent(a)}👉 ${A(d, b)}${ent(c)}`);
    if (k === 'ul') return `<ul style="margin:0 0 18px;padding-left:22px;">${a.map((t) => `<li style="margin:0 0 4px;">${ent(t)}</li>`).join('')}</ul>`;
    if (k === 'sign') return P(`${ent(a)}<br>${ent(b)}`, LETTER[i + 1]?.[0] !== 'ps');
    if (k === 'ps') return `<p style="margin:6px 0 0;">${ent(a)}${A(d, b)}${ent(c)}</p>`;
    return P(ent(a));
  });
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="x-apple-disable-message-reformatting">
<title>${SUBJECT}</title>
<!--
  CAMPAIGN · BLACK FRIDAY 2026 · A LETTER FROM SHADI TO MATE LATTE BUYERS · "${SUBJECT}"
  Preview text: ${PREHEADER}
  From: Shadi from Milonga · reply-to: an inbox Shadi reads · audience: bought the Mate Latte, not subscribed
  A plain letter: no images, one link. Full document for a Klaviyo code template. GENERATED by scripts/make-bf-shadi-buyers.mjs.
-->
<style>
  .unsub-pill a { color:#6B6B6B !important; text-decoration:underline !important; }
  .web-view-line a { color:#6B6B6B !important; }
  @media only screen and (max-width:620px) { .wrap { width:100% !important; } .pad { padding:28px 22px !important; } }
</style>
</head>
<body style="margin:0;padding:0;background-color:#FFFFFF;">
<table role="presentation" width="100%" cellpadding="0" cellspacing="0" border="0" bgcolor="#FFFFFF" style="background:#FFFFFF;">
<tr><td align="center">
<table role="presentation" class="wrap" width="100%" cellpadding="0" cellspacing="0" border="0" style="width:100%;max-width:600px;">
<tr><td class="pad" align="left" style="padding:36px 32px 28px;font-family:Helvetica, Arial, sans-serif;font-size:16px;line-height:1.6;color:#1E1E1E;">

${rows.join('\n')}

</td></tr>
<tr><td class="pad" align="left" style="padding:0 32px 32px;font-family:Helvetica, Arial, sans-serif;font-size:12px;line-height:1.5;color:#6B6B6B;">
<div class="unsub-pill">Don&rsquo;t want these emails anymore? {% unsubscribe 'Unsubscribe' %}</div>
<div class="web-view-line" style="padding-top:6px;">{% web_view %}</div>
<div style="padding-top:10px;">{{ organization.name }} &middot; {{ organization.full_address }}</div>
</td></tr>
</table>
</td></tr>
</table>
</body>
</html>
`;
}

function text() {
  const out = [`SUBJECT: ${SUBJECT}`, `PREVIEW: ${PREHEADER}`, 'FROM: Shadi from Milonga', ''];
  for (const [k, a, b, c, d] of LETTER) {
    if (k === 'l') out.push(`${b}: ${d}`, '');
    else if (k === 'ul') out.push(...a.map((t) => `• ${t}`), '');
    else if (k === 'sign') out.push(a, b, '');
    else if (k === 'ps') out.push(`${a}${b}${c} (${d})`);
    else out.push(a, '');
  }
  return out.join('\n');
}

const h = html(), problems = validate(h).filter((p) => p.rule !== 'fragment-only');
if (problems.length) { console.error(problems); process.exit(1); }
fs.writeFileSync(`${OUT}/bf-shadi-buyers.html`, h);
fs.writeFileSync(`${OUT}/bf-shadi-buyers.txt`, text());
fs.writeFileSync('refine/bf-shadi-buyers.html', `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><style>body{margin:0;background:#2B3A31;padding:28px 0 60px}.inbox{width:600px;max-width:calc(100% - 24px);margin:0 auto 18px;font-family:Helvetica,Arial,sans-serif}.lab{font-size:10px;font-weight:700;letter-spacing:.16em;text-transform:uppercase;color:rgba(255,255,255,.55);margin-bottom:8px}.row{background:#fff;border-radius:12px;padding:13px 16px;display:grid;grid-template-columns:36px 1fr;column-gap:12px;align-items:center}.av{grid-row:1/span 2;width:36px;height:36px;border-radius:50%;background:#004D27;color:#F0EFDF;display:grid;place-items:center;font-weight:900;font-size:13px}.from{font-weight:700;font-size:13px;color:#12331F}.sub{font-size:13px;line-height:1.4;color:#12331F;white-space:nowrap;overflow:hidden;text-overflow:ellipsis}.sub span{color:#6b6b6b}</style></head><body><div class="inbox"><div class="lab">Inbox preview</div><div class="row"><div class="av">S</div><div class="from">Shadi from Milonga</div><div class="sub"><b>${ent(SUBJECT)}</b> <span>&mdash; ${ent(PREHEADER)}</span></div></div></div>${h.slice(h.indexOf('<style>'), h.indexOf('</style>') + 8)}${h.slice(h.indexOf('<table'), h.lastIndexOf('</table>') + 8)}</body></html>`);
console.log('wrote bf-shadi-buyers.html/.txt (validator: pass,', h.length, 'bytes)');
