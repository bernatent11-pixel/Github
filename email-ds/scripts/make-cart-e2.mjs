// Cart abandonment · Mate Latte · Email 2 · "Did something come up?"
//
// A plain letter from Shadi, 1 day after Email 1. Job (flow PDF): name the
// worries (taste, caffeine, subscription), remind pop-up signups of their
// code, one link back to the cart. No discount for anyone else.
//
// Two versions, chosen by a flow split (no conditional tag in the template):
//   code     people who joined "Mate Latte Signups" (the pop-up) in the last
//            3 days, so the reminder never contradicts Welcome E3's
//            "your 15% off ends tonight"
//   no-code  everyone else
//
// Writes exports/klaviyo/cart-e2/cart-e2{,-code}.html + .txt, previews in refine/.
// Usage: node scripts/make-cart-e2.mjs
import fs from 'node:fs';
import { validate } from './validate-klaviyo-email.mjs';

const OUT = 'exports/klaviyo/cart-e2';
fs.mkdirSync(OUT, { recursive: true });
export const SUBJECT = 'Did something come up?';
export const PREHEADER = 'It’s Shadi. Quick check-in about the Mate Latte in your cart.';
const CART = 'https://milonga.life/cart?utm_source=klaviyo&utm_medium=email&utm_campaign=cart_abandon_mate_latte&utm_content=c2_link';

// [kind, text]. 'q' = a worry, in bold. Plain text only; ent() makes it HTML.
const LETTER = [
  ['p', 'Hey {{ first_name|default:\'there\' }},'],
  ['p', 'Shadi here, founder of Milonga 👋'],
  ['p', 'Saw your Mate Latte is still sitting in your cart. Totally get it, life happens LOL. Or maybe something made you pause?'],
  ['p', 'Usually it’s one of these three, so let me answer them real quick:'],
  ['q', '“Will I actually like the taste?”'],
  ['p', 'It tastes like a creamy vanilla latte. Not grassy, not earthy, not “healthy.” Or as Bryant, one of our customers, put it: “The taste was what sold me first.”'],
  ['q', '“Is it a lot of caffeine?”'],
  ['p', '100mg of natural caffeine from yerba mate, about what’s in a cup of coffee. The difference is the 200mg of L-theanine in there, which keeps the energy smooth and steady. No jitters, no crash.'],
  ['q', '“Do I have to subscribe?”'],
  ['p', 'Nope! One-time is totally fine. And if you do join the Mate Mornings Club (30% off 30 or 60 servings), you can skip, pause or cancel anytime. No strings.'],
  ['p', 'And if it’s just not for you, there’s a 30-day money-back guarantee.'],
  ['p', 'If it’s something else, just hit reply and tell me. I read every single one, promise.'],
  ['link', 'Your cart’s right here whenever you’re ready:', 'back to my cart'],
  ['sign', 'Un abrazo,', 'Shadi from Milonga'],
];
const PS = 'P.S. You signed up for our mystery offer, so your code WELCOME15 takes 15% off your first one-time order. Just pop it in at checkout.';

const ent = (s) => s.replace(/&/g, '&amp;').replace(/’/g, '&rsquo;').replace(/‘/g, '&lsquo;').replace(/“/g, '&ldquo;').replace(/”/g, '&rdquo;').replace(/…/g, '&hellip;').replace(/—/g, '&mdash;').replace(/–/g, '&ndash;');
const P = (inner, last) => `<p style="margin:0 0 ${last ? 0 : 18}px;">${inner}</p>`;

function html(code) {
  const rows = LETTER.map(([k, a, b]) => {
    if (k === 'q') return `<p style="margin:0 0 6px;"><strong>${ent(a)}</strong></p>`;
    if (k === 'link') return P(`${ent(a)} <a href="${ent(CART)}" target="_blank" style="color:#004D27;font-weight:bold;text-decoration:underline;">${ent(b)}</a>`);
    if (k === 'sign') return P(`${ent(a)}<br>${ent(b)}`, !code);
    return P(ent(a));
  });
  if (code) rows.push(`<p style="margin:24px 0 0;">${ent(PS).replace('WELCOME15', '<strong>WELCOME15</strong>')}</p>`);
  return `<!--
  CART ABANDONMENT · MATE LATTE · EMAIL 2${code ? ' (POP-UP SIGNUPS, WITH CODE)' : ''} · "${SUBJECT}"
  Preview text: ${PREHEADER}
  From: Shadi from Milonga · reply-to: an inbox Shadi reads · 1 day after Email 1
  ${code ? 'Only for people added to "Mate Latte Signups" in the last 3 days (flow split).' : 'Everyone not in the code branch. No discount.'}
  A plain letter: no images, one link (back to the cart). GENERATED by scripts/make-cart-e2.mjs.
-->
<style>
  .unsub-pill a { color:#6B6B6B !important; text-decoration:underline !important; }
  .web-view-line a { color:#6B6B6B !important; }
  @media only screen and (max-width:620px) { .wrap { width:100% !important; } .pad { padding:28px 22px !important; } }
</style>
<table role="presentation" width="100%" cellpadding="0" cellspacing="0" border="0" bgcolor="#FFFFFF" style="background:#FFFFFF;">
<tr><td align="center">
<table role="presentation" class="wrap" width="600" cellpadding="0" cellspacing="0" border="0" style="width:600px;max-width:600px;">
<tr><td class="pad" align="left" style="padding:36px 32px 28px;font-family:Helvetica, Arial, sans-serif;font-size:16px;line-height:1.6;color:#1E1E1E;">

${rows.join('\n')}

</td></tr>
<tr><td class="pad" align="left" style="padding:0 32px 32px;font-family:Helvetica, Arial, sans-serif;font-size:12px;line-height:1.5;color:#6B6B6B;">
<div class="unsub-pill">Don&rsquo;t want these emails anymore? {% unsubscribe 'Unsubscribe' %}</div>
<div class="web-view-line" style="padding-top:6px;">{% web_view %}</div>
<div style="padding-top:10px;">{{ organization.name }} &middot; {{ organization.full_address }}</div>
</td></tr>
</table>
</td></tr>
</table>
`;
}

function text(code) {
  const out = [`SUBJECT: ${SUBJECT}`, `PREVIEW: ${PREHEADER}`, 'FROM: Shadi from Milonga', ''];
  for (const [k, a, b] of LETTER) {
    if (k === 'link') out.push(a, CART, '');
    else if (k === 'sign') out.push(a, b, '');
    else out.push(a, k === 'q' ? '' : '');
  }
  if (code) out.push(PS, '');
  return out.join('\n').replace(/\n{3,}/g, '\n\n');
}

for (const code of [false, true]) {
  const name = code ? 'cart-e2-code' : 'cart-e2';
  const h = html(code), problems = validate(h);
  if (problems.length) { console.error(name, problems); process.exit(1); }
  fs.writeFileSync(`${OUT}/${name}.html`, h);
  fs.writeFileSync(`${OUT}/${name}.txt`, text(code));
  fs.writeFileSync(`refine/${name}.html`, `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><style>body{margin:0;background:#2B3A31;padding:28px 0 60px}.inbox{width:600px;max-width:calc(100% - 24px);margin:0 auto 18px;font-family:Helvetica,Arial,sans-serif}.lab{font-size:10px;font-weight:700;letter-spacing:.16em;text-transform:uppercase;color:rgba(255,255,255,.55);margin-bottom:8px}.row{background:#fff;border-radius:12px;padding:13px 16px;display:grid;grid-template-columns:36px 1fr;column-gap:12px;align-items:center}.av{grid-row:1/span 2;width:36px;height:36px;border-radius:50%;background:#004D27;color:#F0EFDF;display:grid;place-items:center;font-weight:900;font-size:13px}.from{font-weight:700;font-size:13px;color:#12331F}.sub{font-size:13px;line-height:1.4;color:#12331F;white-space:nowrap;overflow:hidden;text-overflow:ellipsis}.sub span{color:#6b6b6b}</style></head><body><div class="inbox"><div class="lab">Inbox preview${code ? ' · pop-up signups' : ''}</div><div class="row"><div class="av">S</div><div class="from">Shadi from Milonga</div><div class="sub"><b>${ent(SUBJECT)}</b> <span>&mdash; ${ent(PREHEADER)}</span></div></div></div>${h}</body></html>`);
  console.log('wrote', name + '.html/.txt (validator: pass)');
}
