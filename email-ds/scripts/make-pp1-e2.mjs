// Post-purchase (one-time buyers) · Mate Latte · Email 2 · "How’s it going?"
//
// A plain letter from Shadi, day 7 after Placed Order. Job (flow plan): a real
// check-in that asks for a reply (what they like, what they'd change), then a
// review. No selling, no club pitch (that is Email 3).
//
// Writes exports/klaviyo/pp1-e2/pp1-e2.html (full document, for a code template) + .txt, preview in refine/.
// Usage: node scripts/make-pp1-e2.mjs
import fs from 'node:fs';
import { validate } from './validate-klaviyo-email.mjs';

const OUT = 'exports/klaviyo/pp1-e2';
fs.mkdirSync(OUT, { recursive: true });
export const SUBJECT = 'How’s it going?';
export const PREHEADER = 'Not a promo. Just me, checking in on your first week with the Mate Latte.';
// the Mate Latte page, where the reviews are (Judge.me / Okendo widget)
const REVIEW = 'https://milonga.life/products/the-original-mate-latte?utm_source=klaviyo&utm_medium=email&utm_campaign=post_purchase_mate_latte&utm_content=pp2_review';

// [kind, text]. 'q' = a numbered question, in bold. Plain text only; ent() makes it HTML.
const LETTER = [
  ['p', 'Hey {{ first_name|default:\'there\' }},'],
  ['p', 'It’s Shadi, the founder of Milonga 👋'],
  ['p', 'Real quick, this one isn’t a promo. I just wanted to say thank you, for real. You took a chance on a small brand and a drink you’d probably never tried before, and that means a lot to me.'],
  ['p', 'It’s been about a week since you ordered, so if your bag has landed, I’m honestly so curious: how’s it going?'],
  ['p', 'Has it found a spot in your mornings yet? Are you a hot person or an iced person? Oat milk, regular milk, a little cinnamon on top? Has anyone at home started “borrowing” some? 😅'],
  ['p', 'I’d love to hear two things from you:'],
  ['q', '1. What do you love about it so far?'],
  ['q', '2. What would you change?'],
  ['p', 'No wrong answers, and you don’t have to be nice. If something’s off, the taste, the sweetness, the way it mixes, the shipping, I want to know. Just hit reply, even if it’s one line. It comes straight to my inbox, and I read every single one myself.'],
  ['p', 'Little tip in case you haven’t tried it yet: make it iced. 2.5 tablespoons in 8oz of cold milk, stir, pour it over ice. Same Mate Latte, totally different vibe.'],
  ['link', 'And if you’re loving it, could you do me a small favor and leave a quick review? It takes about a minute, and honestly, it’s the thing that helps a small brand like ours the most. Somebody on the fence will read it and give it a try because of you.', 'Leave a review here'],
  ['p', 'Thanks again for being here. It really does mean a lot.'],
  ['sign', 'Un abrazo,', 'Shadi'],
  ['ps', 'P.S. Seriously, hit reply. Even a quick “loving it” or “a bit too sweet for me” makes my day.'],
];

const ent = (s) => s.replace(/&/g, '&amp;').replace(/’/g, '&rsquo;').replace(/‘/g, '&lsquo;').replace(/“/g, '&ldquo;').replace(/”/g, '&rdquo;').replace(/…/g, '&hellip;').replace(/—/g, '&mdash;').replace(/–/g, '&ndash;');
const P = (inner, last) => `<p style="margin:0 0 ${last ? 0 : 18}px;">${inner}</p>`;

function html() {
  const rows = LETTER.map(([k, a, b], i) => {
    if (k === 'q') return `<p style="margin:0 0 ${LETTER[i + 1]?.[0] === 'q' ? 6 : 18}px;"><strong>${ent(a)}</strong></p>`;
    if (k === 'link') return P(`${ent(a)}<br><a href="${ent(REVIEW)}" target="_blank" style="color:#004D27;font-weight:bold;text-decoration:underline;">${ent(b)}</a>`);
    if (k === 'sign') return P(`${ent(a)}<br>${ent(b)}`);
    if (k === 'ps') return `<p style="margin:6px 0 0;">${ent(a)}</p>`;
    return P(ent(a));
  });
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="x-apple-disable-message-reformatting">
<title>${SUBJECT}</title>
<!--
  POST-PURCHASE · ONE-TIME BUYERS · MATE LATTE · EMAIL 2 · "${SUBJECT}"
  Preview text: ${PREHEADER}
  From: Shadi from Milonga · reply-to: an inbox Shadi reads · day 7 after Placed Order
  A plain letter: no images, one link (the review). Full document for a Klaviyo code template. GENERATED by scripts/make-pp1-e2.mjs.
-->
<style>
  .unsub-pill a { color:#6B6B6B !important; text-decoration:underline !important; }
  .web-view-line a { color:#6B6B6B !important; }
  @media only screen and (max-width:620px) { .wrap { width:100% !important; } .pad { padding:28px 22px !important; } }
</style>
</head>
<body style="margin:0;padding:0;background-color:#FFFFFF;">
<table role="presentation" width="100%" cellpadding="0" cellspacing="0" border="0" bgcolor="#FFFFFF" style="background:#FFFFFF;">
<tr><td align="center">
<table role="presentation" class="wrap" width="600" cellpadding="0" cellspacing="0" border="0" style="width:600px;max-width:600px;">
<tr><td class="pad" align="left" style="padding:36px 32px 28px;font-family:Helvetica, Arial, sans-serif;font-size:16px;line-height:1.6;color:#1E1E1E;">

${rows.join('\n')}

</td></tr>
<tr><td class="pad" align="left" style="padding:0 32px 32px;font-family:Helvetica, Arial, sans-serif;font-size:12px;line-height:1.5;color:#6B6B6B;">
<div class="unsub-pill">Don&rsquo;t want these emails anymore? {% unsubscribe 'Unsubscribe' %}</div>
<div class="web-view-line" style="padding-top:6px;">{% web_view %}</div>
<div style="padding-top:10px;">{{ organization.name }} &middot; {{ organization.full_address }}</div>
</td></tr>
</table>
</td></tr>
</table>
</body>
</html>
`;
}

function text() {
  const out = [`SUBJECT: ${SUBJECT}`, `PREVIEW: ${PREHEADER}`, 'FROM: Shadi from Milonga', ''];
  LETTER.forEach(([k, a, b], i) => {
    if (k === 'link') out.push(a, `${b}: ${REVIEW}`, '');
    else if (k === 'sign') out.push(a, b, '');
    else if (k === 'q') out.push(a, ...(LETTER[i + 1]?.[0] === 'q' ? [] : ['']));
    else out.push(a, '');
  });
  return out.join('\n');
}

const h = html(), problems = validate(h).filter((p) => p.rule !== 'fragment-only');
if (problems.length) { console.error(problems); process.exit(1); }
fs.writeFileSync(`${OUT}/pp1-e2.html`, h);
fs.writeFileSync(`${OUT}/pp1-e2.txt`, text());
fs.writeFileSync('refine/pp1-e2.html', `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><style>body{margin:0;background:#2B3A31;padding:28px 0 60px}.inbox{width:600px;max-width:calc(100% - 24px);margin:0 auto 18px;font-family:Helvetica,Arial,sans-serif}.lab{font-size:10px;font-weight:700;letter-spacing:.16em;text-transform:uppercase;color:rgba(255,255,255,.55);margin-bottom:8px}.row{background:#fff;border-radius:12px;padding:13px 16px;display:grid;grid-template-columns:36px 1fr;column-gap:12px;align-items:center}.av{grid-row:1/span 2;width:36px;height:36px;border-radius:50%;background:#004D27;color:#F0EFDF;display:grid;place-items:center;font-weight:900;font-size:13px}.from{font-weight:700;font-size:13px;color:#12331F}.sub{font-size:13px;line-height:1.4;color:#12331F;white-space:nowrap;overflow:hidden;text-overflow:ellipsis}.sub span{color:#6b6b6b}</style></head><body><div class="inbox"><div class="lab">Inbox preview</div><div class="row"><div class="av">S</div><div class="from">Shadi from Milonga</div><div class="sub"><b>${ent(SUBJECT)}</b> <span>&mdash; ${ent(PREHEADER)}</span></div></div></div>${h.slice(h.indexOf('<style>'), h.indexOf('</style>') + 8)}${h.slice(h.indexOf('<table'), h.lastIndexOf('</table>') + 8)}</body></html>`);
console.log('wrote pp1-e2.html/.txt (validator: pass)');
