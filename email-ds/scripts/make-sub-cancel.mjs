// Flow · Subscription cancelled · Email 1 · a plain letter from Shadi with a one-tap "why?" questionnaire
//
// Trigger: Appstle "Subscription canceled Event from Appstle" (metric RABw2w), send about 1 hour after.
// Job (Bernat, 2026-11-12): a written email from Shadi to people who cancel their subscription, with a
// questionnaire to learn why. Appstle's cancellationReason is empty on recent cancellations and Fairing is not
// connected to Klaviyo, so the questionnaire is one tap per answer: each reason is its own link, and Klaviyo
// records the click (Clicked Email, URL contains reason_<key>), so each answer can become a segment or a
// follow-up branch. Or they just reply.
// Written for any subscription (Mate Latte, Lion's Mane or infused cans): it never names the product.
//
// Writes exports/klaviyo/sub-cancel-e1/sub-cancel-e1.html (full document, for a code template) + .txt, preview in refine/.
// Usage: node scripts/make-sub-cancel.mjs
import fs from 'node:fs';
import { validate } from './validate-klaviyo-email.mjs';

const OUT = 'exports/klaviyo/sub-cancel-e1';
fs.mkdirSync(OUT, { recursive: true });
export const SUBJECT = 'can I ask you something?';
export const PREHEADER = 'One tap, and it really helps us.';
const utm = (slot) => `utm_source=klaviyo&utm_medium=email&utm_campaign=sub_cancel_survey&utm_content=${slot}`;
const R = (key) => `https://milonga.life/?${utm(`reason_${key}`)}`;
export const REASONS = [
  ['too_much', 'I had too much at home'],
  ['price', 'It’s a bit too expensive for me'],
  ['taste', 'The taste wasn’t for me'],
  ['one_time', 'I’d rather order when I need it'],
  ['order_issue', 'Something went wrong with my order'],
  ['other', 'Something else'],
];

// [kind, ...]. 'p' text · 'q' the questionnaire · 'sign' · 'ps'
const LETTER = [
  ['p', 'Hey {{ first_name|default:\'there\' }},'],
  ['p', 'Shadi here. I saw you cancelled your subscription. No hard feelings at all, and thank you for giving us a try. It really means a lot.'],
  ['p', 'Can I ask why? It helps us more than you’d think. Just tap the one that fits best:'],
  ['q'],
  ['p', 'Or just hit reply and tell me in your own words. I read every one myself.'],
  ['p', 'And if you ever miss your mornings with us, we’ll be right here.'],
  ['sign', 'Un abrazo,', 'Shadi'],
];

const ent = (s) => s.replace(/&/g, '&amp;').replace(/’/g, '&rsquo;').replace(/‘/g, '&lsquo;').replace(/“/g, '&ldquo;').replace(/”/g, '&rdquo;').replace(/…/g, '&hellip;').replace(/—/g, '&mdash;').replace(/–/g, '&ndash;');
const P = (inner, last) => `<p style="margin:0 0 ${last ? 0 : 18}px;">${inner}</p>`;
const A = (href, text) => `<a href="${href.replace(/&/g, '&amp;')}" target="_blank" style="color:#004D27;font-weight:bold;text-decoration:underline;">${ent(text)}</a>`;

function html() {
  const rows = LETTER.map(([k, a, b, c, d], i) => {
    if (k === 'q') return `<table role="presentation" cellpadding="0" cellspacing="0" border="0" style="margin:0 0 18px;">
${REASONS.map(([key, t]) => `<tr><td style="padding:3px 0;font-family:Helvetica, Arial, sans-serif;font-size:16px;line-height:1.6;color:#1E1E1E;">👉 ${A(R(key), t)}</td></tr>`).join('\n')}
</table>`;
    if (k === 'sign') return P(`${ent(a)}<br>${ent(b)}`, LETTER[i + 1]?.[0] !== 'ps');
    if (k === 'ps') return `<p style="margin:6px 0 0;">${ent(a)}${A(d, b)}${ent(c)}</p>`;
    return P(ent(a));
  });
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="x-apple-disable-message-reformatting">
<title>${SUBJECT}</title>
<!--
  FLOW · SUBSCRIPTION CANCELLED · EMAIL 1 · A LETTER FROM SHADI · "${SUBJECT}"
  Preview text: ${PREHEADER}
  From: Shadi from Milonga · reply-to: an inbox Shadi reads · trigger: Appstle subscription cancelled, about 1 hour after
  A plain letter with a one-tap questionnaire: each answer is its own link (Clicked Email, URL contains reason_<key>).
  Full document for a Klaviyo code template. GENERATED by scripts/make-sub-cancel.mjs.
-->
<style>
  .unsub-pill a { color:#6B6B6B !important; text-decoration:underline !important; }
  .web-view-line a { color:#6B6B6B !important; }
  @media only screen and (max-width:620px) { .wrap { width:100% !important; } .pad { padding:28px 22px !important; } }
</style>
</head>
<body style="margin:0;padding:0;background-color:#FFFFFF;">
<table role="presentation" width="100%" cellpadding="0" cellspacing="0" border="0" bgcolor="#FFFFFF" style="background:#FFFFFF;">
<tr><td align="center">
<table role="presentation" class="wrap" width="100%" cellpadding="0" cellspacing="0" border="0" style="width:100%;max-width:600px;">
<tr><td class="pad" align="left" style="padding:36px 32px 28px;font-family:Helvetica, Arial, sans-serif;font-size:16px;line-height:1.6;color:#1E1E1E;">

${rows.join('\n')}

</td></tr>
<tr><td class="pad" align="left" style="padding:0 32px 32px;font-family:Helvetica, Arial, sans-serif;font-size:12px;line-height:1.5;color:#6B6B6B;">
<div class="unsub-pill">Don&rsquo;t want these emails anymore? {% unsubscribe 'Unsubscribe' %}</div>
<div class="web-view-line" style="padding-top:6px;">{% web_view %}</div>
<div style="padding-top:10px;">{{ organization.name }} &middot; {{ organization.full_address }}</div>
</td></tr>
</table>
</td></tr>
</table>
</body>
</html>
`;
}

function text() {
  const out = [`SUBJECT: ${SUBJECT}`, `PREVIEW: ${PREHEADER}`, 'FROM: Shadi from Milonga', ''];
  for (const [k, a, b, c, d] of LETTER) {
    if (k === 'q') { for (const [key, t] of REASONS) out.push(`- ${t}: ${R(key)}`); out.push(''); }
    else if (k === 'sign') out.push(a, b, '');
    else if (k === 'ps') out.push(`${a}${b}${c} (${d})`);
    else out.push(a, '');
  }
  return out.join('\n');
}

const h = html(), problems = validate(h).filter((p) => p.rule !== 'fragment-only');
if (problems.length) { console.error(problems); process.exit(1); }
fs.writeFileSync(`${OUT}/sub-cancel-e1.html`, h);
fs.writeFileSync(`${OUT}/sub-cancel-e1.txt`, text());
fs.writeFileSync('refine/sub-cancel-e1.html', `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><style>body{margin:0;background:#2B3A31;padding:28px 0 60px}.inbox{width:600px;max-width:calc(100% - 24px);margin:0 auto 18px;font-family:Helvetica,Arial,sans-serif}.lab{font-size:10px;font-weight:700;letter-spacing:.16em;text-transform:uppercase;color:rgba(255,255,255,.55);margin-bottom:8px}.row{background:#fff;border-radius:12px;padding:13px 16px;display:grid;grid-template-columns:36px 1fr;column-gap:12px;align-items:center}.av{grid-row:1/span 2;width:36px;height:36px;border-radius:50%;background:#004D27;color:#F0EFDF;display:grid;place-items:center;font-weight:900;font-size:13px}.from{font-weight:700;font-size:13px;color:#12331F}.sub{font-size:13px;line-height:1.4;color:#12331F;white-space:nowrap;overflow:hidden;text-overflow:ellipsis}.sub span{color:#6b6b6b}</style></head><body><div class="inbox"><div class="lab">Inbox preview</div><div class="row"><div class="av">S</div><div class="from">Shadi from Milonga</div><div class="sub"><b>${ent(SUBJECT)}</b> <span>&mdash; ${ent(PREHEADER)}</span></div></div></div>${h.slice(h.indexOf('<style>'), h.indexOf('</style>') + 8)}${h.slice(h.indexOf('<table'), h.lastIndexOf('</table>') + 8)}</body></html>`);
console.log('wrote sub-cancel-e1.html/.txt (validator: pass,', h.length, 'bytes)');
