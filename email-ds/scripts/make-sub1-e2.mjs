// Post-purchase (Mate Mornings Club subscribers) · Email 2 · "before your next bag ships"
//
// A plain letter from Shadi, day 10 after the subscription starts (Appstle "Create Subscription").
// Job (flow plan): fix the cadence before it turns into a cancel. Thank them, then the two fixes:
// running out early, or too much left. Asks for a reply.
//
// Facts (checked 2026-11-10 on milonga.life/products/the-original-mate-latte.js): both club plans
// (9479323958 for 15 servings, 8837562678 for 30 and 60) deliver every 1 month, the only frequency
// offered, so the letter does NOT offer "every two weeks". Running out early: reply and Shadi moves
// the next order up (Appstle admin). Too much: skip a month (the plans say "skip, pause or cancel
// anytime"), in the Appstle portal.
//
// Writes exports/klaviyo/sub1-e2/sub1-e2.html (full document, for a code template) + .txt, preview in refine/.
// Usage: node scripts/make-sub1-e2.mjs
import fs from 'node:fs';
import { validate } from './validate-klaviyo-email.mjs';

const OUT = 'exports/klaviyo/sub1-e2';
fs.mkdirSync(OUT, { recursive: true });
export const SUBJECT = 'before your next bag ships';
export const PREHEADER = 'A quick note from me, so your deliveries fit how you actually drink it.';
// the Appstle subscription portal (magic-link login), the same as subscribers Email 1
const PORTAL = 'https://milonga.life/apps/subscriptions';

// [kind, text]. 'b' = a line with a bold lead-in ([bold, rest]). Plain text only; ent() makes it HTML.
const LETTER = [
  ['p', 'Hey {{ first_name|default:\'there\' }},'],
  ['p', 'It’s Shadi, the founder of Milonga 👋'],
  ['p', 'Thank you for joining the Mate Mornings Club. Having you with us really means a lot.'],
  ['p', 'Your next bag ships in a few weeks, so I wanted to check in before it does. Is once a month the right rhythm for you?'],
  ['b', 'Running out early?', 'Just reply to this email and I’ll move your next bag up.'],
  ['b', 'Have some left over?', 'Skip a month. It takes a few seconds in your account.'],
  ['link', '', 'Manage my subscription'],
  ['p', 'Either way, hit reply and tell me how your mornings are going. I read every single one myself.'],
  ['sign', 'Un abrazo,', 'Shadi'],
];

const ent = (s) => s.replace(/&/g, '&amp;').replace(/’/g, '&rsquo;').replace(/‘/g, '&lsquo;').replace(/“/g, '&ldquo;').replace(/”/g, '&rdquo;').replace(/…/g, '&hellip;').replace(/—/g, '&mdash;').replace(/–/g, '&ndash;');
const P = (inner, last) => `<p style="margin:0 0 ${last ? 0 : 18}px;">${inner}</p>`;

function html() {
  const rows = LETTER.map(([k, a, b], i) => {
    if (k === 'b') return `<p style="margin:0 0 ${LETTER[i + 1]?.[0] === 'b' ? 10 : 12}px;"><strong>${ent(a)}</strong> ${ent(b)}</p>`;
    if (k === 'link') return P(`<a href="${ent(PORTAL)}" target="_blank" style="color:#004D27;font-weight:bold;text-decoration:underline;">${ent(b)}</a>`);
    if (k === 'sign') return P(`${ent(a)}<br>${ent(b)}`, i === LETTER.length - 1);
    if (k === 'ps') return `<p style="margin:6px 0 0;">${ent(a)}</p>`;
    return P(ent(a));
  });
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="x-apple-disable-message-reformatting">
<title>${SUBJECT}</title>
<!--
  POST-PURCHASE · MATE MORNINGS CLUB SUBSCRIBERS · EMAIL 2 · "${SUBJECT}"
  Preview text: ${PREHEADER}
  From: Shadi from Milonga · reply-to: an inbox Shadi reads · day 10 after the subscription starts
  A plain letter: no images, one link (the subscription portal). Full document for a Klaviyo code template. GENERATED by scripts/make-sub1-e2.mjs.
-->
<style>
  .unsub-pill a { color:#6B6B6B !important; text-decoration:underline !important; }
  .web-view-line a { color:#6B6B6B !important; }
  @media only screen and (max-width:620px) { .wrap { width:100% !important; } .pad { padding:28px 22px !important; } }
</style>
</head>
<body style="margin:0;padding:0;background-color:#FFFFFF;">
<table role="presentation" width="100%" cellpadding="0" cellspacing="0" border="0" bgcolor="#FFFFFF" style="background:#FFFFFF;">
<tr><td align="center">
<table role="presentation" class="wrap" width="600" cellpadding="0" cellspacing="0" border="0" style="width:600px;max-width:600px;">
<tr><td class="pad" align="left" style="padding:36px 32px 28px;font-family:Helvetica, Arial, sans-serif;font-size:16px;line-height:1.6;color:#1E1E1E;">

${rows.join('\n')}

</td></tr>
<tr><td class="pad" align="left" style="padding:0 32px 32px;font-family:Helvetica, Arial, sans-serif;font-size:12px;line-height:1.5;color:#6B6B6B;">
<div class="unsub-pill">Don&rsquo;t want these emails anymore? {% unsubscribe 'Unsubscribe' %}</div>
<div class="web-view-line" style="padding-top:6px;">{% web_view %}</div>
<div style="padding-top:10px;">{{ organization.name }} &middot; {{ organization.full_address }}</div>
</td></tr>
</table>
</td></tr>
</table>
</body>
</html>
`;
}

function text() {
  const out = [`SUBJECT: ${SUBJECT}`, `PREVIEW: ${PREHEADER}`, 'FROM: Shadi from Milonga', ''];
  LETTER.forEach(([k, a, b], i) => {
    if (k === 'link') out.push(`${b}: ${PORTAL}`, '');
    else if (k === 'b') out.push(`${a} ${b}`, ...(LETTER[i + 1]?.[0] === 'b' ? [] : ['']));
    else if (k === 'sign') out.push(a, b, '');
    else out.push(a, '');
  });
  return out.join('\n');
}

const h = html(), problems = validate(h).filter((p) => p.rule !== 'fragment-only');
if (problems.length) { console.error(problems); process.exit(1); }
fs.writeFileSync(`${OUT}/sub1-e2.html`, h);
fs.writeFileSync(`${OUT}/sub1-e2.txt`, text());
fs.writeFileSync('refine/sub1-e2.html', `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><style>body{margin:0;background:#2B3A31;padding:28px 0 60px}.inbox{width:600px;max-width:calc(100% - 24px);margin:0 auto 18px;font-family:Helvetica,Arial,sans-serif}.lab{font-size:10px;font-weight:700;letter-spacing:.16em;text-transform:uppercase;color:rgba(255,255,255,.55);margin-bottom:8px}.row{background:#fff;border-radius:12px;padding:13px 16px;display:grid;grid-template-columns:36px 1fr;column-gap:12px;align-items:center}.av{grid-row:1/span 2;width:36px;height:36px;border-radius:50%;background:#004D27;color:#F0EFDF;display:grid;place-items:center;font-weight:900;font-size:13px}.from{font-weight:700;font-size:13px;color:#12331F}.sub{font-size:13px;line-height:1.4;color:#12331F;white-space:nowrap;overflow:hidden;text-overflow:ellipsis}.sub span{color:#6b6b6b}</style></head><body><div class="inbox"><div class="lab">Inbox preview</div><div class="row"><div class="av">S</div><div class="from">Shadi from Milonga</div><div class="sub"><b>${ent(SUBJECT)}</b> <span>&mdash; ${ent(PREHEADER)}</span></div></div></div>${h.slice(h.indexOf('<style>'), h.indexOf('</style>') + 8)}${h.slice(h.indexOf('<table'), h.lastIndexOf('</table>') + 8)}</body></html>`);
console.log('wrote sub1-e2.html/.txt (validator: pass)');
