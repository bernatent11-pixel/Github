#!/usr/bin/env python3
"""Time the captions in transcript.txt against the speech model's word timings.

transcript.txt is the edited script (one caption per line, with its speaker); asr-words.json is
what the speech model heard, word by word, with a start time for each. This lines the two up:
a word that matches takes the model's time; words that were corrected, added or merged are spread
across the time of whatever they replaced. Writes captions.json for make.mjs.

Usage: python3 build-captions.py      (from this folder; standard library only)
"""
import difflib, json, re, pathlib

here = pathlib.Path(__file__).parent
norm = lambda w: re.sub(r"[^a-z0-9']", '', w.lower().replace('’', "'"))

asr = json.load(open(here / 'asr-words.json'))
asr_n, asr_t = [norm(x['w']) for x in asr], [x['t'] for x in asr]
END = asr_t[-1] + 0.6

caps = []
for line in open(here / 'transcript.txt'):
    line = line.strip()
    if not line or line.startswith('#'): continue
    who, text = line.split(':', 1)
    caps.append({'who': who.strip(), 'words': text.split()})
mine = [(ci, w) for ci, c in enumerate(caps) for w in c['words']]
mine_n = [norm(w) for _, w in mine]

times = [None] * len(mine)
at = lambda i: asr_t[i] if i < len(asr_t) else END
for tag, i1, i2, j1, j2 in difflib.SequenceMatcher(None, asr_n, mine_n, autojunk=False).get_opcodes():
    if tag == 'equal':
        for k in range(j2 - j1): times[j1 + k] = asr_t[i1 + k]
    elif tag in ('replace', 'insert'):
        # spread across the time of what was replaced (or, for an insertion, the gap before the next heard word)
        start = at(i1) if tag == 'replace' else (times[j1 - 1] + 0.12 if j1 and times[j1 - 1] is not None else at(i1) - 0.3)
        end = at(i2) if tag == 'replace' else at(i1)
        end = max(end, start + 0.08 * (j2 - j1))
        for k in range(j2 - j1): times[j1 + k] = start + (end - start) * k / (j2 - j1)
# never backwards, never two words on the same instant
for k in range(1, len(times)):
    times[k] = max(times[k], times[k - 1] + 0.04)

out, k = [], 0
for ci, c in enumerate(caps):
    ws = [[w, round(times[k + n], 2)] for n, w in enumerate(c['words'])]
    k += len(c['words'])
    out.append({'who': c['who'], 'words': ws})
for ci, c in enumerate(out):
    nxt = out[ci + 1]['words'][0][1] if ci + 1 < len(out) else END
    c['end'] = round(min(nxt, c['words'][-1][1] + 0.7), 2)

json.dump({'note': 'Generated by build-captions.py from transcript.txt and asr-words.json. who: S = Shadi, J = James. words: [word, start seconds].', 'captions': out},
          open(here / 'captions.json', 'w'), indent=None, separators=(',', ':'), ensure_ascii=False)
for c in out:
    dur = c['end'] - c['words'][0][1]
    print(f"{c['who']} {c['words'][0][1]:7.2f} -> {c['end']:7.2f} ({dur:4.1f}s, {len(' '.join(w for w, _ in c['words'])):2d} ch)  {' '.join(w for w, _ in c['words'])}")
print(len(out), 'captions,', sum(len(c['words']) for c in out), 'words')
