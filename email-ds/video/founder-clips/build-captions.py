#!/usr/bin/env python3
"""Time the captions in a clip's script.txt against the speech model's word timings.

script.txt is the caption script: one caption per line, its lines split by " / ", and the line
that carries the key words wrapped in *asterisks* (that one is set in the large gold italic; the
rest in small capitals). asr-words.json is what the speech model heard, word by word, with a
start time for each. This lines the two up: a word that matches takes the model's time; words that
are written differently from how they were heard ("400 mg" for "four hundred milligrams",
"L-theanine", "&") are spread across the time of whatever they stand for. Writes captions.json
for make.mjs.

Options go in braces at the end of a caption line:
  {offer}  {big}     larger key words (big is for a number or one short word)
  {dark}             forest ink, for a light background
  {x=320} {y=800}    centre of the caption in the 1080 x 1920 frame
  {max=500}          widest a line may be
  {end=12.3}         when the caption is done (default: when the next one starts, or 0.75 s after its last word)
  {cut=7.95}         remove it at exactly this time with no fade
A line "@cuts 80 211 ..." lists the clip's jump cuts, each as the number of the first frame of
the new shot (frame 0 is the first frame). make.mjs moves the caption change nearest each cut
onto the cut itself, so no caption hangs over into the next shot or arrives ahead of it.

Usage: python3 video/founder-clips/build-captions.py <clip folder>      (standard library only)
"""
import difflib, json, re, pathlib, sys

here = pathlib.Path(sys.argv[1])
def norm(w):
    w = w.lower().replace('’', "'").replace('&', 'and')
    return re.sub(r"[^a-z0-9']", '', w)

asr = json.load(open(here / 'asr-words.json'))
asr_n, asr_t = [norm(x['w']) for x in asr], [x['t'] for x in asr]
END = asr_t[-1] + 0.9

caps, cuts = [], []
for raw in open(here / 'script.txt', encoding='utf8'):
    raw = raw.strip()
    if not raw or raw.startswith('#'): continue
    if raw.startswith('@cuts'):
        cuts += [int(x) for x in raw.split()[1:]]; continue
    opts = {}
    for o in re.findall(r'\{([^}]*)\}', raw):
        for tok in o.split():
            if tok in ('offer', 'big'): opts['size'] = tok
            elif tok == 'dark': opts['ink'] = 'dark'
            else:
                k, v = tok.split('='); opts[k] = float(v)
    raw = re.sub(r'\{[^}]*\}', '', raw).strip()
    lines = []
    for part in raw.split(' / '):
        part = part.strip()
        kind = 'ital' if part.startswith('*') and part.endswith('*') else 'caps'
        lines.append([kind, part.strip('*').split()])
    caps.append({'opts': opts, 'lines': lines})

mine = [w for c in caps for _, ws in c['lines'] for w in ws]
mine_n = [norm(w) for w in mine]
times = [None] * len(mine)
at = lambda i: asr_t[i] if i < len(asr_t) else END
for tag, i1, i2, j1, j2 in difflib.SequenceMatcher(None, asr_n, mine_n, autojunk=False).get_opcodes():
    if tag == 'equal':
        for k in range(j2 - j1): times[j1 + k] = asr_t[i1 + k]
    elif tag in ('replace', 'insert'):
        # spread across the time of what was replaced (or, for an added word, the gap before the next heard word)
        start = at(i1) if tag == 'replace' else (times[j1 - 1] + 0.12 if j1 and times[j1 - 1] is not None else at(i1) - 0.3)
        end = at(i2) if tag == 'replace' else at(i1)
        end = max(end, start + 0.08 * (j2 - j1))
        for k in range(j2 - j1): times[j1 + k] = start + (end - start) * k / (j2 - j1)
        print(f"  note: {' '.join(mine[j1:j2])!r} written for heard {' '.join(x['w'] for x in asr[i1:i2])!r} at {start:.2f} s")
    elif tag == 'delete':
        print(f"  note: heard but not in the script: {' '.join(x['w'] for x in asr[i1:i2])!r} at {at(i1):.2f} s")
# never backwards, never two words on the same instant
for k in range(1, len(times)):
    times[k] = max(times[k], times[k - 1] + 0.04)

out, k = [], 0
for c in caps:
    lines = []
    for kind, ws in c['lines']:
        lines.append([kind, [[w, round(times[k + n], 2)] for n, w in enumerate(ws)]])
        k += len(ws)
    out.append({**{a: (int(b) if isinstance(b, float) and b == int(b) and a != 'end' and a != 'cut' else b) for a, b in c['opts'].items()}, 'lines': lines})
first = lambda c: c['lines'][0][1][0][1]
last = lambda c: c['lines'][-1][1][-1][1]
for i, c in enumerate(out):
    nxt = first(out[i + 1]) if i + 1 < len(out) else END
    c.setdefault('end', round(min(nxt, last(c) + 0.75), 2))

text = lambda c: ' / '.join(' '.join(w for w, _ in ws) for _, ws in c['lines'])
body = ',\n'.join('    ' + json.dumps(c, ensure_ascii=False, separators=(', ', ': ')) for c in out)
note = ('Generated by build-captions.py from script.txt and asr-words.json; edit script.txt, not this file. One caption per entry. '
        'Each line is [kind, [[word, start seconds], ...]]: caps = lead-in words, small Gotham Black capitals; ital = the key words, large gold serif bold italic. '
        'Optional: size = offer or big; ink = dark; x, y = centre in the 1080 x 1920 frame; max = widest line; cut = remove at this time with no fade. '
        'cuts = the jump cuts in the footage, as the first frame of each new shot.')
open(here / 'captions.json', 'w', encoding='utf8').write('{\n  "note": ' + json.dumps(note) + ',\n  "cuts": ' + json.dumps(cuts) + ',\n  "captions": [\n' + body + '\n  ]\n}\n')
for c in out:
    print(f"{first(c):6.2f} -> {c['end']:6.2f} ({c['end'] - first(c):4.2f}s) {c.get('size', ''):5s} {text(c)}")
print(len(out), 'captions,', len(mine), 'words')
